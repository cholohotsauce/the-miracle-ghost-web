// Bakes the world outline for the Ghost Sightings map into src/content/worldMap.ts:
// one SVG path for all land (Natural Earth 1:110m, via world-atlas), drawn in the Natural Earth projection,
// plus the scale and offset the page needs to place pins on it. Antarctica is cropped off.
//
// Usage: node scripts/bake-world-map.mjs

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);

const W = 1000;
// Fit the world from the Arctic down to the southern tip of South America
const frame = {
  type: "Feature",
  geometry: {
    type: "Polygon",
    coordinates: [[[-180, 84], [180, 84], [180, -58], [-180, -58], [-180, 84]].reverse()],
  },
};
const projection = geoNaturalEarth1().fitWidth(W, frame);
const [[, y0], [, y1]] = geoPath(projection).bounds(frame);
const H = Math.ceil(y1 - y0);
projection.translate([projection.translate()[0], projection.translate()[1] - y0]);

const d = geoPath(projection.precision(0.3), null)(land)
  .replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));

const out = `// Generated by scripts/bake-world-map.mjs from Natural Earth (public domain). Do not edit by hand.

/** Map size in SVG units */
export const WORLD_SIZE = { width: ${W}, height: ${H} };

/** Natural Earth projection scale and offset, so pins land in the same place as the outline */
export const WORLD_PROJECTION = { scale: ${projection.scale().toFixed(4)}, x: ${projection.translate()[0].toFixed(3)}, y: ${projection.translate()[1].toFixed(3)} };

/** Every coastline, as one SVG path */
export const WORLD_LAND = "${d}";
`;
fs.writeFileSync(path.join(ROOT, "src/content/worldMap.ts"), out);
console.log(`wrote worldMap.ts: ${W}x${H}, ${(d.length / 1024).toFixed(1)} KB path`);
